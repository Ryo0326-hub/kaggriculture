@pytest.mark.parametrize("case", CREWS, ids=lambda c: c["id"])
def test_seat_relabeling_preserves_our_plan_on_recorded_large_farms(policy, case):
    obs, cfg = case["observation"], configuration(case)
    original = invoke(policy, obs, cfg)
    mirrored = copy.deepcopy(obs)
    mirrored["player"] = 1 - obs["player"]
    mirrored["farms"].reverse()
    # Derived metamorphic case: our same private state stays ours, no rival private data.
    policy["agent"].__globals__["_MEMORY"].clear()
    assert invoke(policy, mirrored, cfg) == original


@pytest.mark.parametrize("history", RECORDS["histories"], ids=lambda h: h["id"])
def test_short_original_history_handles_dawn_reset_and_terminal_delivery(policy, history):
    cfg = configuration(history)
    assert len(history["observations"]) == 4
    assert history["state_indices"] == list(
        range(history["state_indices"][0], history["state_indices"][0] + 4)
    )
    memory = policy["agent"].__globals__["_MEMORY"]
    modes = {}
    for mode in ("warm", "warm-repeat", "cold"):
        memory.clear()
        actions = []
        for obs in history["observations"]:
            if mode == "cold":
                memory.clear()
            actions.append(invoke(policy, obs, cfg))
        modes[mode] = actions
    assert modes["warm"] == modes["warm-repeat"]
    if history["kind"] == "dawn-rehire":
        before, after = history["observations"][:2]
        assert before["hour"] == 23 and after["hour"] == 0
        assert after["day"] == before["day"] + 1
        assert after["farms"][after["player"]]["hands"] == []
    else:
        assert history["state_indices"] == [715, 716, 717, 718]


def test_tier_fixture_has_both_seats_and_does_not_invent_missing_events():
    assert len(CASES) == 136 and len(RECORDS["histories"]) == 36
    assert len({(c["episode"], c["seat"], c["state_index"]) for c in CASES}) == len(CASES)
    for tier, episodes in GROUPS.items():
        for episode in episodes:
            assert {c["seat"] for c in CASES if c["episode"] == episode and c["tier"] == tier} == {
                0,
                1,
            }
    no_floor_game = [c for c in CASES if c["episode"] == 108377042]
    assert all("price-floor" not in c["conditions"] for c in no_floor_game)
    assert all(
        "action" not in c["observation"] and "rewards" not in c["observation"] for c in CASES
    )


def test_archive_writer_refuses_to_replace_different_prior_bytes(tmp_path):
    target = tmp_path / "recording.json"
    save_once(target, b"original data")
    save_once(target, b"original data")
    with pytest.raises(FileExistsError):
        save_once(target, b"different data")
    assert target.read_bytes() == b"original data"
